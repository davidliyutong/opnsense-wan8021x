/*
 * Render one wpa_supplicant configuration per enabled supplicant into
 * /var/etc/wan8021x and the index (supplicants.json) the daemon starts from.
 *
 * Everything is written to a staging directory first and swapped in only
 * when complete, so a failure (e.g. a full disk) leaves the previous set
 * intact and exits non-zero. rc.d/wan8021x serializes runs.
 */

require_once 'config.inc';
require_once 'util.inc';

use OPNsense\Wan8021x\Wan8021x;

const CONF_DIR = '/var/etc/wan8021x';
const CTRL_DIR = '/var/run/wan8021x';

/**
 * wpa_supplicant parses an unquoted string value as hex, which sidesteps any
 * quoting or escaping issue with user supplied identities and passwords.
 */
function wpa_string(string $value): string
{
    return bin2hex($value);
}

function fail(string $message)
{
    global $stage;
    syslog(LOG_ERR, "wan8021x: {$message}, keeping the previous configuration");
    fwrite(STDERR, "wan8021x: {$message}\n");
    if (!empty($stage) && is_dir($stage)) {
        array_map('unlink', glob("{$stage}/*"));
        rmdir($stage);
    }
    exit(1);
}

/**
 * @param string $name file name inside the configuration directory
 */
function write_file(string $name, string $content)
{
    global $stage;
    $path = "{$stage}/{$name}";
    if (file_put_contents($path, $content) !== strlen($content) || !chmod($path, 0600)) {
        fail("cannot write {$name}");
    }
}

function ca_pem(string $refid): ?string
{
    foreach (config_read_array('ca', false) as $ca) {
        if ($ca['refid'] == $refid && !empty($ca['crt'])) {
            return base64_decode($ca['crt']);
        }
    }
    return null;
}

/* files carry their final paths (wpa_supplicant reads the CA from there), they are written below $stage */
$stage = CONF_DIR . '.new';
$previous = CONF_DIR . '.old';
foreach ([$stage, $previous] as $dir) {
    if (is_dir($dir)) {
        array_map('unlink', glob("{$dir}/*"));
        rmdir($dir);
    }
}
if (!mkdir($stage, 0700)) {
    $stage = null;
    fail('cannot create ' . CONF_DIR . '.new');
}

$mdl = new Wan8021x();
$index = [];

if ($mdl->general->enabled->isEqual('1')) {
    foreach ($mdl->supplicants->supplicant->iterateItems() as $uuid => $sup) {
        if (!$sup->enabled->isEqual('1')) {
            continue;
        }
        $ifname = $sup->interface->getValue();
        $device = $mdl->deviceOf($ifname);
        if ($device == '') {
            syslog(LOG_ERR, "wan8021x: interface {$ifname} has no usable device, skipped");
            continue;
        }

        $network = [
            'key_mgmt=IEEE8021X',
            'eapol_flags=0',
            'eap=' . $sup->eap_method->getValue(),
            'identity=' . wpa_string($sup->identity->getValue()),
            'password=' . wpa_string($sup->password->getValue()),
            'phase2="auth=' . $sup->phase2->getValue() . '"',
        ];
        if (!$sup->anonymous_identity->isEmpty()) {
            $network[] = 'anonymous_identity=' . wpa_string($sup->anonymous_identity->getValue());
        }
        if (!$sup->ca->isEmpty()) {
            $pem = ca_pem($sup->ca->getValue());
            if ($pem === null) {
                syslog(LOG_ERR, "wan8021x: certificate authority for {$ifname} not found, skipped");
                continue;
            }
            write_file("{$device}-ca.pem", $pem);
            $network[] = 'ca_cert="' . CONF_DIR . "/{$device}-ca.pem" . '"';
            if (!$sup->domain_match->isEmpty()) {
                $network[] = 'domain_suffix_match=' . wpa_string($sup->domain_match->getValue());
            }
        }

        $lines = array_merge(
            [
                '# generated by os-wan8021x, do not edit',
                'ctrl_interface=' . CTRL_DIR,
                'ap_scan=0',
                'eapol_version=' . $sup->eapol_version->getValue(),
                'network={',
            ],
            array_map(function ($line) {
                return "\t" . $line;
            }, $network),
            ['}', '']
        );
        write_file("{$device}.conf", implode("\n", $lines));

        $index[] = [
            'uuid' => $uuid,
            'interface' => $ifname,
            'description' => $sup->description->getValue(),
            'device' => $device,
            'config' => CONF_DIR . "/{$device}.conf",
        ];
    }
}

write_file('supplicants.json', json_encode([
    'debug' => $mdl->general->debug->isEqual('1'),
    'supplicants' => $index,
], JSON_PRETTY_PRINT) . "\n");

/* the daemon is stopped while this runs, nothing reads the directory during the swap */
if (is_dir(CONF_DIR) && !rename(CONF_DIR, $previous)) {
    fail('cannot replace ' . CONF_DIR);
}
if (!rename($stage, CONF_DIR)) {
    rename($previous, CONF_DIR);
    fail('cannot replace ' . CONF_DIR);
}
$stage = null;
if (is_dir($previous)) {
    array_map('unlink', glob("{$previous}/*"));
    rmdir($previous);
}
